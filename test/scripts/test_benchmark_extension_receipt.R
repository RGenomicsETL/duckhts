source("scripts/benchmark_extension_receipt.R")
root <- normalizePath(".")
revision <- benchmark_evidence_revision(root)
extension <- benchmark_extension_path(root, "build/release/duckhts.duckdb_extension")
value <- list(path = extension, binding = "htslib_distclean_make_release",
              sha256 = benchmark_evidence_sha256(extension))
receipt <- tempfile("benchmark-extension-receipt-", fileext = ".tsv")
invisible(benchmark_evidence_write_extension_receipt(receipt, revision, value))
observed <- benchmark_evidence_read_extension_receipt(receipt, root, extension, revision)
stopifnot(identical(observed, value))
failed <- function(expression) inherits(try(force(expression), silent = TRUE), "try-error")
stopifnot(failed(benchmark_evidence_read_extension_receipt(
  receipt, root, extension, strrep("0", 40L))))
record <- utils::read.delim(receipt, colClasses = "character", check.names = FALSE)
record$value[record$field == "sha256"] <- strrep("0", 64L)
utils::write.table(record, receipt, sep = "\t", quote = FALSE, row.names = FALSE)
stopifnot(failed(benchmark_evidence_read_extension_receipt(receipt, root, extension, revision)))
unlink(receipt)
message("benchmark extension receipt: OK")
